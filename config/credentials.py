import os
import re

SHELLMATE_DIR = os.path.expanduser("~/.shellmate")
ENV_FILE = os.path.join(SHELLMATE_DIR, ".env")

CREDENTIAL_KEYS = {
    "GROQ_API_KEY": {
        "label": "Groq API Key",
        "description": "For AI risk analysis (get at https://console.groq.com/keys)",
        "doc_url": "https://console.groq.com/keys",
        "required": False,
    },
    "OPENROUTER_API_KEY": {
        "label": "OpenRouter API Key",
        "description": "For AI remediation suggestions (get at https://openrouter.ai/keys)",
        "doc_url": "https://openrouter.ai/keys",
        "required": False,
    },
    "CONTEXT7_API_KEY": {
        "label": "Context7 API Key",
        "description": "For documentation lookup (get at https://context7.com)",
        "doc_url": "https://context7.com",
        "required": False,
    },
}


def load_env():
    if not os.path.exists(ENV_FILE):
        return {}
    env = {}
    try:
        with open(ENV_FILE, "r") as f:
            for line in f:
                line = line.strip()
                if not line or line.startswith("#"):
                    continue
                if "=" in line:
                    key, _, value = line.partition("=")
                    key = key.strip()
                    value = value.strip().strip("\"'")
                    env[key] = value
    except OSError:
        pass
    return env


def save_env(env_dict):
    os.makedirs(SHELLMATE_DIR, exist_ok=True)
    with open(ENV_FILE, "w") as f:
        f.write("# ShellMate Credentials\n")
        f.write("# Generated by `shellmate configure`\n")
        f.write("# Add your API keys below (one per line, KEY=VALUE format)\n\n")
        for key in CREDENTIAL_KEYS:
            value = env_dict.get(key, "")
            if value:
                f.write(f"{key}={value}\n")
            else:
                f.write(f"# {key}=\n")


def get_credential_status():
    env = load_env()
    result = {}
    for key, info in CREDENTIAL_KEYS.items():
        value = env.get(key, os.environ.get(key, ""))
        result[key] = {
            "configured": bool(value),
            "label": info["label"],
            "masked": _mask_key(value) if value else None,
        }
    return result


def get_api_key(key_name):
    env = load_env()
    return env.get(key_name) or os.environ.get(key_name)


def _mask_key(key):
    if len(key) <= 8:
        return key[:4] + ("*" * (len(key) - 4))
    return key[:4] + ("*" * (len(key) - 8)) + key[-4:]


def export_script(shell="bash"):
    env = load_env()
    lines = []
    for key in CREDENTIAL_KEYS:
        value = env.get(key)
        if value:
            if shell == "powershell":
                lines.append(f"$env:{key} = '{value}'")
            else:
                lines.append(f"export {key}='{value}'")
    return "\n".join(lines)
