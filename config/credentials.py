import os
import stat
from pathlib import Path
from config.paths import CREDENTIALS_FILE, ensure_dirs


CREDENTIAL_KEYS = {
    "GROQ_API_KEY": {
        "label": "Groq API Key",
        "description": "For AI risk analysis (get at https://console.groq.com/keys)",
        "doc_url": "https://console.groq.com/keys",
        "required": False,
    },
    "OPENROUTER_API_KEY": {
        "label": "OpenRouter API Key",
        "description": "For AI remediation suggestions (get at https://openrouter.ai/keys)",
        "doc_url": "https://openrouter.ai/keys",
        "required": False,
    },
    "CONTEXT7_API_KEY": {
        "label": "Context7 API Key",
        "description": "For documentation lookup (get at https://context7.com)",
        "doc_url": "https://context7.com",
        "required": False,
    },
}


def load_env() -> dict:
    if not CREDENTIALS_FILE.exists():
        return {}
    env = {}
    try:
        with open(CREDENTIALS_FILE, "r") as f:
            for line in f:
                line = line.strip()
                if not line or line.startswith("#"):
                    continue
                if "=" in line:
                    key, _, value = line.partition("=")
                    key = key.strip()
                    value = value.strip().strip("\"'")
                    env[key] = value
    except OSError:
        pass
    return env


def save_env(env_dict: dict) -> None:
    ensure_dirs()
    with open(CREDENTIALS_FILE, "w") as f:
        f.write("# ShellMate Credentials\n")
        f.write("# Generated by `sm config`\n")
        f.write("# Add your API keys below (one per line, KEY=VALUE format)\n\n")
        for key in CREDENTIAL_KEYS:
            value = env_dict.get(key, "")
            if value:
                f.write(f"{key}={value}\n")
            else:
                f.write(f"# {key}=\n")

    if os.name != "nt":
        try:
            CREDENTIALS_FILE.chmod(stat.S_IRUSR | stat.S_IWUSR)
        except OSError:
            pass


def get_credential_status() -> dict:
    env = load_env()
    result = {}
    for key, info in CREDENTIAL_KEYS.items():
        value = env.get(key, os.environ.get(key, ""))
        result[key] = {
            "configured": bool(value),
            "label": info["label"],
            "masked": _mask_key(value) if value else None,
        }
    return result


def get_api_key(key_name: str) -> str:
    env = load_env()
    return os.environ.get(key_name, "") or env.get(key_name, "")


def _mask_key(key: str) -> str:
    if len(key) <= 8:
        return key[:4] + ("*" * (len(key) - 4))
    return key[:4] + ("*" * (len(key) - 8)) + key[-4:]


def export_script(shell: str = "bash") -> str:
    env = load_env()
    lines = []
    for key in CREDENTIAL_KEYS:
        value = env.get(key)
        if value:
            if shell == "powershell":
                lines.append(f"$env:{key} = '{value}'")
            else:
                lines.append(f"export {key}='{value}'")
    return "\n".join(lines)